import JSZip from 'jszip'
import { MODES, parseNum, type ModeKey, type Settings } from '../modes'
import type { Frame, Reason } from './extract'

const MATCH: Record<string, string> = {
  'Sequential': 'sequential', 'Sequential + loop': 'sequential', 'Sequential + vocab tree': 'vocab_tree',
  'Spatial (GPS) + vocab tree': 'vocab_tree', 'Exhaustive': 'exhaustive',
}

export type BundleInput = {
  mode: ModeKey
  settings: Settings
  project: string
  frames: Frame[]
  reasons: Reason[]
  clipNames: Record<string, string>
}

export async function buildBundle(inp: BundleInput, onProgress: (p: number) => void): Promise<Blob> {
  const zip = new JSZip()
  const kept = inp.frames.filter((_, i) => !inp.reasons[i])
  const r = inp.settings.rows
  const cam = String(r.camera)
  const meta = {
    generator: 'Splat Studio',
    project: inp.project,
    captureType: MODES[inp.mode].label,
    extraction: inp.settings.extract,
    camera: { model: cam, matcher: r.matcher, features: parseNum(r.features) },
    training: { iterations: parseNum(r.iters), shDegree: parseNum(r.sh), densifyUntil: parseNum(r.densifyUntil), maxGaussians: parseNum(r.maxg) },
    presetOptions: r,
    frames: kept.map((f, i) => ({ file: `images/frame_${String(i + 1).padStart(5, '0')}.jpg`, source: inp.clipNames[f.clipId], t: +f.t.toFixed(3), sharpness: +f.score.toFixed(1), width: f.w, height: f.h })),
  }
  zip.file('splat_studio.json', JSON.stringify(meta, null, 2))
  const cameraType = /fisheye/i.test(cam) ? 'fisheye' : 'perspective'
  zip.file('train.sh', `#!/usr/bin/env bash
# Generated by Splat Studio (${MODES[inp.mode].label} preset). Requires nerfstudio (COLMAP + gsplat) on a CUDA machine.
# Settings that nerfstudio's splatfacto does not expose directly are recorded in splat_studio.json.
set -euo pipefail
cd "$(dirname "$0")"
ns-process-data images --data images --output-dir processed \\
  --camera-type ${cameraType} --matching-method ${MATCH[String(r.matcher)] ?? 'sequential'}
ns-train splatfacto --data processed \\
  --max-num-iterations ${parseNum(r.iters, 30000)} \\
  --pipeline.model.sh-degree ${parseNum(r.sh, 3)} \\
  --pipeline.model.stop-split-at ${parseNum(r.densifyUntil, 15000)}
# Then: ns-export gaussian-splat --load-config outputs/<run>/splatfacto/<timestamp>/config.yml --output-dir exports
# and open the resulting .ply in the Train & view step.
`)
  const folder = zip.folder('images')!
  kept.forEach((f, i) => folder.file(`frame_${String(i + 1).padStart(5, '0')}.jpg`, f.blob))
  return zip.generateAsync({ type: 'blob', compression: 'STORE' }, (m) => onProgress(m.percent / 100))
}
